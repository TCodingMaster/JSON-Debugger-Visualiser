"""Run the full lab (all concepts × symbols) and export results for mock.html."""

from __future__ import annotations

import csv
import json
from datetime import datetime, timezone
from pathlib import Path

from . import engine, features, metrics, scoring, strategies
from .data import INSTRUMENTS, get_instrument

ROOT = Path(__file__).resolve().parent.parent
GOALS = {
    "target_wr": 0.60,
    "target_avg_rr": 1.5,
    "planned_rr": 2.0,
    "sizing": {s: {"contracts": i.contracts, "point_value": i.point_value, "tick": i.tick}
               for s, i in INSTRUMENTS.items()},
}


def load_concepts() -> list[dict]:
    return json.loads((ROOT / "data" / "concepts.json").read_text())["concepts"]


def run_all(datasets: dict, strategy_ids: list[str], cfg: engine.EngineConfig,
            overrides: dict | None = None, log=print) -> dict:
    """datasets: {symbol: DataFrame}. Returns {sid: {symbol: (trades, metrics)}}."""
    out: dict = {sid: {} for sid in strategy_ids}
    for sym, df in datasets.items():
        inst = get_instrument(sym)
        feat = features.build(df, inst.tick)
        log(f"[{sym}] {len(df):,} bars  {df.index[0]:%Y-%m-%d} → {df.index[-1]:%Y-%m-%d}")
        for sid in strategy_ids:
            setups = strategies.generate(sid, feat, inst, overrides)
            trades = engine.run(feat, setups, inst, cfg)
            m = metrics.summarize(trades)
            out[sid][sym] = (trades, m)
            if m["trades"]:
                log(f"   {sid:16s} trades {m['trades']:4d}  WR {m['win_rate']:6.1%}  payoff {m['payoff_ratio']:4.2f}"
                    f"  exp {m['expectancy_r']:+.3f}R  PF {m['profit_factor']:5.2f}  net ${m['net_pnl']:>10,.0f}"
                    f"  maxDD ${m['max_dd']:>8,.0f}")
            else:
                log(f"   {sid:16s} no trades")
    return out


def export(results: dict, data_mode: str, data_note: str, out_dir: Path | None = None) -> Path:
    out_dir = out_dir or ROOT
    res_dir = out_dir / "results"
    res_dir.mkdir(parents=True, exist_ok=True)
    concepts = load_concepts()
    by_id = {c["id"]: c for c in concepts}

    payload_results, scores = {}, {}
    for sid, per_sym in results.items():
        payload_results[sid] = {}
        for sym, (trades, m) in per_sym.items():
            with open(res_dir / f"trades_{sid}_{sym}.csv", "w", newline="") as fh:
                w = csv.DictWriter(fh, fieldnames=list(engine.Trade.__dataclass_fields__))
                w.writeheader()
                for t in trades:
                    w.writerow(t.to_dict())
            payload_results[sid][sym] = {
                "metrics": m,
                "equity": metrics.equity_series(trades),
                "r_hist": metrics.r_histogram(trades),
                "monthly": metrics.monthly(trades),
                "trades_sample": [t.to_dict() for t in trades[-50:]],
            }
    for c in concepts:
        per_sym = {s: v["metrics"] for s, v in payload_results.get(c["id"], {}).items()}
        scores[c["id"]] = scoring.score_concept(c, per_sym, GOALS)

    payload = {
        "generated_at": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "data_mode": data_mode,
        "data_note": data_note,
        "goals": GOALS,
        "weights": scoring.WEIGHTS,
        "concepts": [by_id[k] for k in by_id],
        "results": payload_results,
        "scores": scores,
    }
    text = json.dumps(payload, default=_json_default, allow_nan=False)
    (res_dir / "lab-data.json").write_text(text)
    target = out_dir / "lab-data.js"
    target.write_text("// generated by `python lab.py backtest` — do not edit\nwindow.LAB_DATA = " + text + ";\n")
    (res_dir / "summary.md").write_text(summary_markdown(payload))
    return target


def _json_default(o):
    if hasattr(o, "item"):
        return o.item()
    raise TypeError(type(o))


def summary_markdown(p: dict) -> str:
    rows = []
    for c in p["concepts"]:
        s = p["scores"][c["id"]]
        best = s["best_symbol"]
        m = p["results"].get(c["id"], {}).get(best, {}).get("metrics", {}) if best else {}
        rows.append((s["total"], c, s, best, m))
    rows.sort(key=lambda r: -r[0])
    lines = [
        f"# Futures Strategy Lab — results ({p['data_mode']} data)",
        "",
        f"Generated {p['generated_at']}. {p['data_note']}",
        "",
        "Plan: fixed 2R per trade, 2 MNQ or 1 MGC; goals WR ≥ 60 %, avg RR ≥ 1.5.",
        "",
        "| # | Concept | Score | Grade | Best | Trades | WR | Payoff | Exp (R) | PF | Net $ | Max DD $ |",
        "|---|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    for k, (total, c, s, best, m) in enumerate(rows, 1):
        if m.get("trades"):
            lines.append(f"| {k} | {c['name']} | {total:.0f}{'*' if s['provisional'] else ''} | {s['grade']} | {best} | "
                         f"{m['trades']} | {m['win_rate']:.1%} | {m['payoff_ratio']:.2f} | {m['expectancy_r']:+.3f} | "
                         f"{m['profit_factor']:.2f} | {m['net_pnl']:,.0f} | {m['max_dd']:,.0f} |")
        else:
            lines.append(f"| {k} | {c['name']} | {total:.0f}* | {s['grade']} | – | 0 | – | – | – | – | – | – |")
    lines += ["", "\\* provisional: fewer than 10 trades, score built from qualitative components only.", ""]
    return "\n".join(lines)
